const dir = path.dirname(fileURLToPath(import.meta.url));
const snap = fs.readFileSync(path.join(dir, '_source_snapshot.js'), 'utf8').split(/\r?\n/);

function extractBalanced(src, openIdx) {
  let i = openIdx;
  let depth = 0;
  let inStr = null;
  let esc = false;
  for (; i < src.length; i++) {
    const ch = src[i];
    if (inStr) {
      if (esc) {
        esc = false;
        continue;
      }
      if (ch === '\\') {
        esc = true;
        continue;
      }
      if (ch === inStr) inStr = null;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === '`') {
      inStr = ch;
      continue;
    }
    if (ch === '/' && src[i + 1] === '/') {
      while (i < src.length && src[i] !== '\n') i++;
      continue;
    }
    if (ch === '{') depth++;
    else if (ch === '}') {
      depth--;
      if (depth === 0) return src.slice(openIdx, i + 1);
    }
  }
  throw new Error('unbalanced');
}

const seqFn = snap.slice(1163, 1575).join('\n'); // async function fillSequential(){...}
const open = seqFn.indexOf('{');
let inner = extractBalanced(seqFn, open).slice(1, -1);

// Budget + filled counter on kernel
inner = inner
  .replace(/\b_ajaxWaitBudgetMs\b/g, 'k.ajaxWaitBudgetMs')
  .replace(/\b_ajaxNotLoadedCount\b/g, 'k.ajaxNotLoadedCount')
  .replace(/([^.\w])filled\s*\+=/g, '$1k.filled +=')
  .replace(/([^.\w])filled\s*=(?!=)/g, '$1k.filled =')
  // free identifier uses (e.g. console.log(..., filled, ...))
  .replace(/([^.\w'"\]])filled\b(?!\s*:)/g, '$1k.filled')
  .replace(/'k\.filled'/g, "'filled'")
  .replace(/"k\.filled"/g, '"filled"')
  // avoid shadowing kernel k in .some(k => ...)
  .replace(/PRIORITY_KEYS\.some\(k\s*=>/g, 'PRIORITY_KEYS.some((pk) =>')
  .replace(
    /fieldLabel\.includes\(k\) \|\| selector\.toLowerCase\(\)\.includes\(k\)/g,
    'fieldLabel.includes(pk) || selector.toLowerCase().includes(pk)'
  );

// Strip comment-only lines to keep file smaller (still may be >200 — OK inside bundle)
inner = inner
  .split('\n')
  .filter((l) => {
    const t = l.trim();
    if (!t) return false;
    if (t.startsWith('//')) return false;
    return true;
  })
  .join('\n');

